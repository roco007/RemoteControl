import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'shared/protocol-manifest.json'), 'utf8'));
const ts = '// Generated by shared/generate.mjs. Edit protocol-manifest.json.\n' +
  `export const PROTOCOL = ${JSON.stringify(manifest, null, 2)} as const;\n` +
  `export const MessageType = ${JSON.stringify(Object.fromEntries(manifest.messageTypes.map(t => [t, t])), null, 2)} as const;\n`;
const swift = '// Generated by shared/generate.mjs. Edit protocol-manifest.json.\nimport Foundation\n\npublic enum Wire {\n' +
  Object.entries(manifest).map(([k, v]) => `    public static let ${k} = ${JSON.stringify(v)}`).join('\n') + '\n}\n';
for (const [path, content] of [['shared/constants.ts', ts], ['receiver/Sources/ReceiverCore/ProtocolConstants.swift', swift]]) {
  const absolute = resolve(root, path);
  if (process.argv.includes('--check')) {
    if (readFileSync(absolute, 'utf8') !== content) throw new Error(`Protocol drift: ${path}. Run npm run protocol:generate.`);
  } else { mkdirSync(dirname(absolute), { recursive: true }); writeFileSync(absolute, content); }
}
